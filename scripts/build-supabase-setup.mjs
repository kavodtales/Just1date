import { createHash } from "node:crypto";
import { URL } from "node:url";
import { readFile, readdir, mkdir, writeFile } from "node:fs/promises";

const directory = new URL("../supabase/migrations/", import.meta.url);
export async function buildSetupSql() {
  const names = (await readdir(directory))
    .filter((name) => name.endsWith(".sql"))
    .sort();
  let sql = `-- Generated by npm run db:bundle. Do not edit; migrations are authoritative.
-- Run as the database owner in Supabase SQL Editor. No accounts or secret keys are seeded.
begin;
select pg_advisory_xact_lock(871920);
create table if not exists public.schema_migrations(name text primary key,checksum text not null,applied_at timestamptz not null default now());
alter table public.schema_migrations enable row level security;
revoke all on public.schema_migrations from public,anon,authenticated;
grant all on public.schema_migrations to service_role;
`;
  for (const name of names) {
    const source = (await readFile(new URL(name, directory), "utf8")).replace(
      /\r\n/g,
      "\n",
    );
    const checksum = createHash("sha256").update(source).digest("hex");
    if (source.includes("$j1d_source$") || source.includes("$j1d_apply$"))
      throw new Error(`Reserved SQL delimiter in ${name}`);
    sql += `
-- ${name}
do $j1d_apply$
declare previous text;
begin
  select checksum into previous from public.schema_migrations where name='${name}';
  if found then
    if previous <> '${checksum}' then
      raise exception 'Applied migration checksum mismatch: ${name}';
    end if;
  else
    execute $j1d_source$${source}$j1d_source$;
    insert into public.schema_migrations(name,checksum) values('${name}','${checksum}');
  end if;
end
$j1d_apply$;
`;
  }
  return sql + "\ncommit;\n";
}
const output = new URL("../supabase/setup/", import.meta.url);
await mkdir(output, { recursive: true });
await writeFile(new URL("production.sql", output), await buildSetupSql());
console.log("Generated supabase/setup/production.sql");
